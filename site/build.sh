#!/usr/bin/env bash
# Assembles the GitHub Pages site into _site/ (or the directory given).
# Run from the repository root: site/build.sh [outdir]
# The interactive demo on the page is fed by flutterkill itself: this script
# builds the synthetic workspace from demo/setup.sh (a temporary HOME with fake
# projects and caches, the same one the README GIF is recorded on) and runs
# only read-only commands against it (scan --json, --list). It never runs
# apply, --yes or the TUI, and never looks at the real HOME. The recording is
# converted from demo/demo.gif; without ffmpeg the page falls back to the GIF.
# Needs Go, git and python3; ffmpeg is optional.
set -euo pipefail
out=${1:-_site}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
real_home=$HOME

rm -rf "$out"
mkdir -p "$out"
cp site/index.html site/style.css site/app.js site/favicon.svg site/og.png \
   site/404.html site/robots.txt site/sitemap.xml "$out"/
cp demo/demo.gif "$out"/demo.gif

# Read-only runs against demo/setup.sh's fake HOME, in a subshell so its
# exports stay there. env -i keeps every cache override (XDG_CACHE_HOME,
# PUB_CACHE, GRADLE_USER_HOME, ...) from pointing back at this machine.
(
  trap 'cd /; { command -v hdiutil >/dev/null && hdiutil detach -quiet /tmp/flutterkill-demo/home 2>/dev/null; } || true; rm -rf /tmp/flutterkill-demo' EXIT
  # shellcheck source=../demo/setup.sh
  source demo/setup.sh >/dev/null
  set -euo pipefail
  [ "$HOME" != "$real_home" ] || { echo "demo HOME is the real HOME; stopping" >&2; exit 1; }
  fk() {
    env -i HOME="$HOME" PATH="$PATH" DEVELOPER_DIR=/nonexistent TZ=UTC NO_COLOR=1 \
      GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1 flutterkill "$@"
  }
  fk scan --json "$HOME/dev" >"$tmp/scan.json"
  fk --list "$HOME/dev" >"$tmp/list.txt"
)

# Fail the build if anything from outside the demo HOME slipped in.
python3 - "$tmp/scan.json" "$tmp/list.txt" "$real_home" "${USER:-}" <<'PY'
import json, sys
scan_path, list_path, home, user = sys.argv[1:5]
scan = json.load(open(scan_path))
assert scan["schema_version"] == 1 and scan["items"], "unexpected scan"
for it in scan["items"]:
    assert it["path"].startswith("~/"), "path outside the demo HOME: " + it["path"]
for name in (scan_path, list_path):
    text = open(name).read()
    # The user name only as a path component: Flutter's own windows/runner and
    # linux/runner folders would otherwise trip it on CI, whose user is "runner".
    for bad in [home, "/Users/", "/home/", "flutterkill-demo"] + ([f"/{user}/"] if len(user) > 2 else []):
        assert bad not in text, f"{name} mentions {bad!r}"
PY

{
  printf '// Generated by site/build.sh: flutterkill scan --json on demo/setup.sh'"'"'s synthetic HOME. Dummy data, not a real machine.\n'
  printf 'window.FLUTTERKILL_SAMPLE = {"scan": '
  cat "$tmp/scan.json"
  printf '};\n'
} >"$out/sample.js"

# The page's --list block shows the same run.
python3 - "$out/index.html" "$tmp/list.txt" <<'PY'
import html, re, sys
page, listing = sys.argv[1], open(sys.argv[2]).read().rstrip("\n")
s = open(page).read()
s, n = re.subn(r"<!--list-->.*?<!--/list-->", lambda m: "<!--list-->" + html.escape(listing, quote=False) + "<!--/list-->", s, flags=re.S)
assert n == 1, "list marker missing"
open(page, "w").write(s)
PY

# Latest release tag, when tags are available (CI fetches them).
if tag=$(git describe --tags --abbrev=0 2>/dev/null); then
  sed -i.bak "s|<!--version-->[^<]*<!--/version-->|$tag|" "$out/index.html" && rm -f "$out/index.html.bak"
fi

if command -v ffmpeg >/dev/null; then
  ffmpeg -loglevel error -y -i demo/demo.gif -movflags +faststart -pix_fmt yuv420p \
    -vf "scale=trunc(iw/2)*2:trunc(ih/2)*2" -c:v libx264 -crf 24 -preset slow "$out/demo.mp4"
  ffmpeg -loglevel error -y -i demo/demo.gif -vf "select=eq(n\,100)" -frames:v 1 -c:v libwebp -quality 82 "$out/demo-poster.webp" || true
else
  echo "ffmpeg not found: the page will show demo.gif instead of a video" >&2
fi
ls -la "$out"
